const out = {};
const missing = [];
for (const [name, slug] of Object.entries(MAP)) {
  if (slug && bySlug[slug]) {
    out[name] = { h: bySlug[slug].hex, p: bySlug[slug].path };
  } else {
    missing.push(name + (slug ? ' (slug "' + slug + '" not found)' : ' (no slug)'));
  }
}

const header = '/*\n' +
  ' * StackPeek — technology logos (auto-generated by scripts/gen_logos.js).\n' +
  ' * Brand marks from Simple Icons (https://simpleicons.org), CC0 1.0.\n' +
  ' * Map: technology name -> { h: brand hex, p: single SVG path (viewBox 0 0 24 24) }.\n' +
  ' * Technologies without an entry render a lettered monogram in the UI.\n' +
  ' */\n';
