/*
 * Generate stackpeek/data/logos.js — a map of technology name -> { hex, path }
 * using Simple Icons (CC0). Inlined so the extension needs no extra files and
 * makes zero network requests. Unmatched technologies fall back to a monogram
 * tile in the UI.
 */
const fs = require('fs');
const path = require('path');
const si = require('simple-icons');

// slug -> icon object index
const bySlug = {};
for (const k of Object.keys(si)) {
  const ic = si[k];
  if (ic && ic.slug) { bySlug[ic.slug] = ic; }
}

